// 获取字符数据指针
const uint8_t *font_get_char_data(char c) {
    if (c < FONT_FIRST_CHAR || c > FONT_LAST_CHAR) {
        // 返回空格
        return font_5x7[0];
    }
    return font_5x7[c - FONT_FIRST_CHAR];
}

// 字符宽度（固定为5）
uint8_t font_get_char_width(char c) {
    (void)c; // 未使用参数
    return FONT_WIDTH;
}

// 字符高度（固定为7）
uint8_t font_get_char_height(void) {
    return FONT_HEIGHT;
}

// 字符串宽度（像素）
uint8_t font_get_string_width(const char *str) {
    if (str == NULL) return 0;

    uint8_t width = 0;
    while (*str) {
        width += font_get_char_width(*str) + 1; // 字符宽度 + 1像素间距
        str++;
    }
    if (width > 0) width -= 1; // 减去最后一个字符的间距

    return width;
}

// 绘制字符到缓冲区
// buffer: 二维缓冲区，按行优先，每个字节代表一行中的8个像素（仅使用低5位）
// buffer_width: 缓冲区宽度（以像素计）
// buffer_height: 缓冲区高度（以像素计）
void font_draw_char(char c, uint8_t x, uint8_t y, uint8_t *buffer, uint8_t buffer_width, uint8_t buffer_height) {
    if (x >= buffer_width || y >= buffer_height) return;

    const uint8_t *char_data = font_get_char_data(c);

    // 绘制每个列
    for (uint8_t col = 0; col < FONT_WIDTH; col++) {
        uint8_t col_data = char_data[col];
        uint8_t col_x = x + col;

        if (col_x >= buffer_width) break;

        // 绘制列中的每个行
        for (uint8_t row = 0; row < FONT_HEIGHT; row++) {
            uint8_t row_y = y + row;

            if (row_y >= buffer_height) break;

            // 检查位是否置位（注意：字体数据中LSB可能是顶部行，也可能是底部行）
            // 这里假设位0对应顶部行（行0）
            if (col_data & (1 << row)) {
                // 设置像素
                // 计算缓冲区索引：行优先
                uint16_t index = row_y * ((buffer_width + 7) / 8) + (col_x / 8);
                uint8_t bit_mask = 1 << (7 - (col_x % 8)); // 假设高位在左

                buffer[index] |= bit_mask;
            }
        }
    }
}

// 绘制字符串到缓冲区
void font_draw_string(const char *str, uint8_t x, uint8_t y, uint8_t *buffer, uint8_t buffer_width, uint8_t buffer_height) {
    if (str == NULL) return;

    uint8_t current_x = x;

    while (*str) {
        font_draw_char(*str, current_x, y, buffer, buffer_width, buffer_height);
        current_x += font_get_char_width(*str) + 1; // 字符宽度 + 1像素间距

        str++;
    }
}
